"""Music by place (map, round, boss, story, island and closet), a twinkle with a streak, jingles, a volume slider;
"Read everything aloud": off by default; when on, Pip reads his lines, questions, hints, explanations and pop-ups."""
from serve import *
c = Check('music and reading aloud')
STUB = "window.__said=[];if(window.speechSynthesis){speechSynthesis.speak=u=>__said.push(u.text);speechSynthesis.cancel=()=>{}}"
with sync_playwright() as p:
    b = launch(p)
    for w in (1280, 390):
        ctx, pg, errs = open_page(b, w, 900)
        pg.evaluate(STUB + ";window.__tourTest=0")
        c.ok(pg.evaluate("theme") == 'map', f'{w}: the map theme on the map')
        pg.evaluate("start(byId('mult'))"); pg.wait_for_timeout(500)
        c.ok(pg.evaluate("theme") == 'play', f'{w}: a calmer theme in a round')
        c.ok(pg.evaluate("__said.length") == 0, f'{w}: nothing is read aloud by default')
        pg.evaluate("S.streak=2;judge(true,null)"); pg.wait_for_timeout(200)
        c.ok(pg.evaluate("mLayer") == 1, f'{w}: a streak adds a twinkle to the music')
        pg.evaluate("openStory()"); pg.wait_for_timeout(300)
        c.ok(pg.evaluate("theme") == 'story', f'{w}: story theme')
        pg.evaluate("ovOpen&&closeOverlay();openCloset()"); pg.wait_for_timeout(300)
        c.ok(pg.evaluate("theme") == 'home', f'{w}: cozy theme in the closet')
        pg.evaluate("renderMap();start(byId('boss'))"); pg.wait_for_timeout(500)
        c.ok(pg.evaluate("theme") in ('boss', 'map'), f'{w}: boss theme (or the map if the boss is locked): ' + pg.evaluate("theme"))
        c.ok(pg.evaluate("(()=>{try{jingle('win');jingle('level');jingle('unlock');jingle('quest');return true}catch(e){return String(e)}})()") is True, f'{w}: jingles play')
        # reading aloud
        pg.evaluate("ovOpen&&closeOverlay();renderMap();G.settings.read=true;save();__said=[];start(byId('mult'))"); pg.wait_for_timeout(600)
        if pg.evaluate("typeof TR!=='undefined'&&TR.on"): pg.keyboard.press('Escape'); pg.wait_for_timeout(200)
        said = pg.evaluate("__said")
        q = pg.evaluate("htmlToSpeech(S.qs[0].speak||S.qs[0].prompt)")
        c.ok(len(said) >= 2 and q in said, f'{w}: Pip greets and reads the question: {said[:2]}')
        pg.evaluate("__said=[];judge(false,null)"); pg.wait_for_timeout(200)
        c.ok(any(x.startswith('Hint') for x in pg.evaluate("__said")), f'{w}: the hint is read: {pg.evaluate("__said")[:3]}')
        pg.evaluate("__said=[];judge(false,null)"); pg.wait_for_timeout(200)
        c.ok(len(pg.evaluate("__said")) >= 2, f'{w}: the explanation after a miss is read')
        pg.evaluate("__said=[];overlay('<h2>New on the map!</h2><p>Thunder Tower opened.</p><button class=go onclick=closeOverlay()>OK</button>')"); pg.wait_for_timeout(200)
        c.ok(any('Thunder Tower' in x for x in pg.evaluate("__said")), f'{w}: pop-ups are read')
        pg.evaluate("closeOverlay();__said=[];CL.unlockUntil=Date.now()+600000;openParent()"); pg.wait_for_timeout(500)
        c.ok(pg.evaluate("__said.length") == 0, f'{w}: Parents\' Corner is never read aloud')
        pg.click('.ptabs [data-pt="set"]'); pg.wait_for_timeout(300)
        c.ok(pg.locator('#setRead').count() == 1 and pg.get_attribute('#setRead', 'aria-checked') == 'true', f'{w}: the setting is in Parents')
        pg.fill('#setMvol', '40'); pg.dispatch_event('#setMvol', 'input'); pg.wait_for_timeout(100)
        c.ok(pg.evaluate("localStorage.getItem('pip-mvol')") == '40' and abs(pg.evaluate("mVol") - 0.4) < 0.01, f'{w}: music volume is saved')
        c.ok(not errs, f'{w}: page errors {errs[:3]}')
        ctx.close()
c.done()

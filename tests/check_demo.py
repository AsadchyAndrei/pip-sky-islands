"""Teacher demo (?demo=teacher): a sample class without signing in, nothing saved, and leaving it restores the device."""
from serve import *
c = Check('teacher demo')
with sync_playwright() as p:
    b = launch(p)
    for w in (1280, 390):
        ctx = b.new_context(viewport={'width': w, 'height': 900}, service_workers='block'); ctx.route('**/*', router)
        ctx.add_init_script("if(!sessionStorage.getItem('s')){localStorage.clear();localStorage.setItem('pip-last-uid','realuid');localStorage.setItem('pip-cloud-realuid','{\"keep\":1}');sessionStorage.setItem('s','1')}")
        pg = ctx.new_page(); errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.goto(ORIGIN + '?demo=teacher')
        pg.wait_for_function("typeof curScreen!=='undefined'&&curScreen==='teach'&&!!TC.cur&&!!TC.mem[TC.cur]&&!!document.querySelector('.grps')", timeout=20000)
        c.ok(pg.evaluate("classRows(curClass()).length") == 12, f'{w}: 12 sample students')
        c.ok(pg.evaluate("classRows(curClass()).filter(r=>r.sum&&Object.values(r.sum.sk).some(v=>v[0]===2)).length") >= 6, f'{w}: some skills mastered')
        c.ok(pg.locator('#demoBar').is_visible() and 'Nothing is saved' in pg.text_content('#demoBar'), f'{w}: demo ribbon')
        pg.click('[data-tt="tasks"]'); pg.wait_for_timeout(400)
        c.ok('learning fractions' in pg.input_value('#fnote') and pg.locator('.tasks li').count() == 2, f'{w}: sample tasks and note')
        pg.click('[data-tisl="mult"]'); pg.click('#tAdd'); pg.wait_for_timeout(300)
        c.ok(pg.locator('.tasks li').count() == 3, f'{w}: a task can be added in the demo')
        pg.click('[data-tt="kids"]'); pg.wait_for_timeout(300)
        c.ok(pg.locator('.roster li').count() >= 8, f'{w}: students on classroom devices')
        pg.click('#gcImp'); pg.wait_for_function("/turned off/.test((document.querySelector('#gcMsg')||{}).textContent||'')", timeout=5000)
        pg.evaluate("closeOverlay()")
        c.ok(pg.evaluate("Object.keys(localStorage).some(k=>k.includes('pipdemo'))"), f'{w}: demo keeps its things apart')
        pg.click('#demoExit'); pg.wait_for_timeout(2500)
        r = pg.evaluate("[location.search,localStorage.getItem('pip-last-uid'),localStorage.getItem('pip-cloud-realuid'),Object.keys(localStorage).filter(k=>k.includes('pipdemo')||k.startsWith('pip-demo')).length,!!(window.PipCloud&&window.PipCloud.demo)]")
        c.ok(r == ['', 'realuid', '{"keep":1}', 0, False], f'{w}: leaving the demo restores the device: {r}')
        c.ok(not errs, f'{w}: page errors {errs[:3]}')
        ctx.close()
c.done()
